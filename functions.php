/** Url of a file inside the theme's copied legacy asset tree (_assets_/...). */
function vineyard_asset( $path = '' ) {
	return trailingslashit( get_template_directory_uri() ) . '_assets_/' . ltrim( $path, '/' );
}

/* ------------------------------------------------------- legacy url maps */
/**
 * Old page path (e.g. "government/city_council2.php") => new WordPress path ("government/city-council2/").
 * Generated by scripts/build_content.py into inc/legacy-map.php.
 */
function vineyard_legacy_map() {
	static $map = null;
	if ( null === $map ) {
		$file = get_template_directory() . '/inc/legacy-map.php';
		$map  = file_exists( $file ) ? include $file : array();
	}
	return $map;
}

/** Permalink for an old Revize page path. Falls back to the home URL. */
function vineyard_url( $old_path ) {
	$old_path = ltrim( $old_path, '/' );
	$map      = vineyard_legacy_map();
	if ( '' === $old_path || 'index.php' === $old_path ) {
		return home_url( '/' );
	}
	return isset( $map[ $old_path ] ) ? home_url( '/' . $map[ $old_path ] ) : home_url( '/' );
}

/**
 * Media Library URL for a file that lived at the site root of the old site
 * (e.g. "Headshots/IMG_1037 - Copy.jpg"). import.sh stores the old path in the
 * attachment meta "_vc_old_path". Falls back to the theme copy, then empty string.
 */
function vineyard_media_url( $old_path ) {
	static $index = null;
	$old_path = ltrim( rawurldecode( $old_path ), '/' );
	if ( null === $index ) {
		$index = get_transient( 'vineyard_media_index' );
		if ( ! is_array( $index ) ) {
			global $wpdb;
			$index = array();
			$rows  = $wpdb->get_results( "SELECT post_id, meta_value FROM {$wpdb->postmeta} WHERE meta_key = '_vc_old_path'" ); // phpcs:ignore
			foreach ( (array) $rows as $r ) {
				$index[ $r->meta_value ] = (int) $r->post_id;
			}
			set_transient( 'vineyard_media_index', $index, HOUR_IN_SECONDS );
		}
	}
	if ( isset( $index[ $old_path ] ) ) {
		$url = wp_get_attachment_url( $index[ $old_path ] );
		if ( $url ) {
			return $url;
		}
	}
	// Fallback: legacy file copied next to the theme (scripts/import.sh does not need it).
	$local = get_template_directory() . '/_assets_/' . $old_path;
	return file_exists( $local ) ? vineyard_asset( $old_path ) : '';
}
