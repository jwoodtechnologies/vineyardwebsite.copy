// The old site searched via /search.php?q=...; map to WordPress search.
add_action( 'template_redirect', function () {
	if ( isset( $_GET['q'] ) && ! isset( $_GET['s'] ) && is_front_page() ) { // phpcs:ignore
		wp_safe_redirect( add_query_arg( 's', rawurlencode( wp_unslash( $_GET['q'] ) ), home_url( '/' ) ) ); // phpcs:ignore
		exit;
	}
} );

