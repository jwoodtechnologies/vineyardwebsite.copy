/* --------------------------------------------------- per-page legacy meta */
/** Fetch the legacy page chrome stored by import.sh in post meta. */
function vineyard_meta( $key, $default = '' ) {
	$v = get_post_meta( get_the_ID(), $key, true );
	return '' === $v || false === $v ? $default : $v;
}

/** Banner slides (array of image URLs) for the inner-page slider. */
function vineyard_banner_images() {
	$raw = vineyard_meta( 'vc_banner_images', '[]' );
	$arr = json_decode( $raw, true );
	return is_array( $arr ) ? $arr : array();
}

