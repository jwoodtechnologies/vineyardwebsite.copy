#!/usr/bin/env python3
"""Build media-import-N.xml (WXR attachment items) + media-manifest.csv for WordPress Importer ("Download and import
file attachments" ticked: the importer fetches wp:attachment_url from the live server and adds it to the Media Library).

  python3 -I scripts/build_media_wxr.py [BASE_URL]
  BASE_URL default: https://vineyard54.wpcomstaging.com/wp-content/themes/vineyard/files

Chunks: at most 60 files and 150 MB of source files each. The water / Consumer Confidence reports go first in their own
chunk(s). Every attachment gets a UNIQUE post_date because WordPress Importer treats title+post_date as "already exists".
Outputs to content/: media-import-N.xml, media-manifest.csv
"""
import csv, json, mimetypes, os, re, sys, urllib.parse as up
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = (sys.argv[1] if len(sys.argv) > 1 else "https://vineyard54.wpcomstaging.com/wp-content/themes/vineyard/files").rstrip("/")
MAX_FILES, MAX_BYTES, LIMIT = 60, 150 * 1000 * 1000, 95 * 1024 * 1024
MIME = {".pdf": "application/pdf", ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".gif": "image/gif",
        ".docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        ".doc": "application/msword", ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        ".pptx": "application/vnd.openxmlformats-officedocument.presentationml.presentation"}

rows = [r for r in csv.DictReader(open(ROOT / "content" / "media.csv", newline="", encoding="utf-8"))]
files = []
for r in rows:
    sz = os.path.getsize(ROOT / r["local_path"])
    if sz < LIMIT:  # the 140 MB PDF is not deployed
        files.append((r["old_path"], sz))
files.sort()

# ---- water / Consumer Confidence group: linked from the Water Quality Reports page + file names that say so
pat = re.compile(r"water quality|consumer confidence|drinking water|water report|\bccr\b", re.I)
linked = set()
for m in json.load(open(ROOT / "content" / "manifest.json")):
    if m["slug"] == "water-quality-reports":
        html = (ROOT / "content" / m["content_file"]).read_text(encoding="utf-8")
        for h in re.findall(r'href="([^"]+)"', html):
            linked.add(up.unquote(up.urlparse(h).path).lstrip("/"))
water = [f for f in files if f[0] in linked or pat.search(f[0])]
wset = {f[0] for f in water}
rest = [f for f in files if f[0] not in wset]

def chunk(items):
    out, cur, tot = [], [], 0
    for f in items:
        if cur and (len(cur) >= MAX_FILES or tot + f[1] > MAX_BYTES):
            out.append(cur); cur, tot = [], 0
        cur.append(f); tot += f[1]
    if cur: out.append(cur)
    return out
chunks = chunk(water) + chunk(rest)

def cd(s): return "<![CDATA[" + str(s).replace("]]>", "]]]]><![CDATA[>") + "]]>"
def title_of(path):
    t = os.path.basename(path)
    while os.path.splitext(t)[1].lower() in MIME:      # also handles names like "x.pdf.pdf"
        t = os.path.splitext(t)[0]
    t = t.replace("_", " ")
    return re.sub(r"\s+", " ", t).strip()
def slug_of(path):
    return re.sub(r"[^a-z0-9]+", "-", title_of(path).lower()).strip("-")[:190] or "file"

HEAD = ('<?xml version="1.0" encoding="UTF-8" ?>\n<!-- Generated by scripts/build_media_wxr.py. Import with Tools > Import > WordPress and TICK '
        '"Download and import file attachments". -->\n<rss version="2.0" xmlns:excerpt="http://wordpress.org/export/1.2/excerpt/" '
        'xmlns:content="http://purl.org/rss/1.0/modules/content/" xmlns:wfw="http://wellformedweb.org/CommentAPI/" '
        'xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:wp="http://wordpress.org/export/1.2/">\n<channel>\n'
        '\t<title>Vineyard City files</title>\n\t<link>https://www.vineyardutah.gov</link>\n\t<description></description>\n'
        '\t<language>en-US</language>\n\t<wp:wxr_version>1.2</wp:wxr_version>\n'
        '\t<wp:base_site_url>https://www.vineyardutah.gov</wp:base_site_url>\n\t<wp:base_blog_url>https://www.vineyardutah.gov</wp:base_blog_url>\n'
        '\t<wp:author><wp:author_id>1</wp:author_id><wp:author_login><![CDATA[admin]]></wp:author_login><wp:author_email><![CDATA[admin@example.com]]></wp:author_email>'
        '<wp:author_display_name><![CDATA[admin]]></wp:author_display_name><wp:author_first_name><![CDATA[]]></wp:author_first_name><wp:author_last_name><![CDATA[]]></wp:author_last_name></wp:author>\n'
        '\t<generator>https://wordpress.org/?v=6.8</generator>\n')
out_dir = ROOT / "content"
for old in out_dir.glob("media-import-*.xml"): old.unlink()
t0 = datetime(2026, 11, 10, 0, 0, 0)  # unique second per file across ALL chunks (importer: same title + same date == "already exists")
n = 0; man = []
for ci, ch in enumerate(chunks, 1):
    xml = HEAD
    for path, sz in ch:
        n += 1
        d = (t0 + timedelta(seconds=n)).strftime("%Y-%m-%d %H:%M:%S")
        url = BASE + "/" + "/".join(up.quote(seg, safe="") for seg in path.split("/"))
        mime = MIME.get(os.path.splitext(path)[1].lower()) or mimetypes.guess_type(path)[0] or "application/octet-stream"
        xml += ("\t<item>\n\t\t<title>%s</title>\n\t\t<link>%s</link>\n\t\t<pubDate>Tue, 10 Nov 2026 00:00:00 +0000</pubDate>\n\t\t<dc:creator>%s</dc:creator>\n"
                "\t\t<guid isPermaLink=\"false\">%s</guid>\n\t\t<description></description>\n\t\t<content:encoded>%s</content:encoded>\n\t\t<excerpt:encoded>%s</excerpt:encoded>\n"
                "\t\t<wp:post_id>%d</wp:post_id>\n\t\t<wp:post_date>%s</wp:post_date>\n\t\t<wp:post_date_gmt>%s</wp:post_date_gmt>\n\t\t<wp:post_modified>%s</wp:post_modified>\n\t\t<wp:post_modified_gmt>%s</wp:post_modified_gmt>\n"
                "\t\t<wp:comment_status>%s</wp:comment_status>\n\t\t<wp:ping_status>%s</wp:ping_status>\n\t\t<wp:post_name>%s</wp:post_name>\n\t\t<wp:status>%s</wp:status>\n"
                "\t\t<wp:post_parent>0</wp:post_parent>\n\t\t<wp:menu_order>0</wp:menu_order>\n\t\t<wp:post_type>%s</wp:post_type>\n\t\t<wp:post_mime_type>%s</wp:post_mime_type>\n\t\t<wp:post_password>%s</wp:post_password>\n\t\t<wp:is_sticky>0</wp:is_sticky>\n"
                "\t\t<wp:attachment_url>%s</wp:attachment_url>\n"
                "\t\t<wp:postmeta><wp:meta_key>%s</wp:meta_key><wp:meta_value>%s</wp:meta_value></wp:postmeta>\n\t</item>\n") % (
            cd(title_of(path)), up.quote(url, safe=":/%"), cd("admin"), up.quote(url, safe=":/%"), cd(""), cd(""), 20000 + n,
            cd(d), cd(d), cd(d), cd(d), cd("closed"), cd("closed"), cd(slug_of(path)), cd("inherit"), cd("attachment"), cd(mime), cd(""),
            cd(url), cd("_vc_old_path"), cd(path))
        man.append((ci, path, sz))
    (out_dir / f"media-import-{ci}.xml").write_text(xml + "</channel>\n</rss>\n", encoding="utf-8")
with open(out_dir / "media-manifest.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f); w.writerow(["chunk", "filename", "size"]); w.writerows(man)
nw = len(chunk(water))
print(f"{n} files -> {len(chunks)} chunks (chunk 1{'-%d' % nw if nw > 1 else ''} = water/Consumer Confidence reports: {len(water)} files)")
for ci, ch in enumerate(chunks, 1):
    print(f"  media-import-{ci}.xml: {len(ch)} files, {sum(s for _, s in ch)/1e6:.0f} MB")
